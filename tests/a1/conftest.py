"""Shared fixtures for the Paper A1 tests: a small A1 demo dataset and settings that point at it.

The dataset is written once per session into a temporary folder, never into experiments/a1/, so the
tests neither need nor disturb a dataset someone generated by hand.
"""

import logging
from pathlib import Path

import pytest
import yaml

from experiments.a1.make_demo_data import main as make_demo_data
from yg_eo_soilnet.a1.settings import settings_from_mapping

PROJECT_ROOT = Path(__file__).resolve().parents[2]
A1_CONFIGS = PROJECT_ROOT / "configs" / "a1"
# Small enough to stay fast, large enough that every carbonate class and region holds 30+ points.
N_DEMO_POINTS = 480


@pytest.fixture(scope="session")
def a1_demo_n_points() -> int:
    """How many points the demo dataset of these tests holds."""
    return N_DEMO_POINTS


@pytest.fixture(scope="session")
def a1_demo_dir(tmp_path_factory) -> Path:
    """A freshly generated A1 demo dataset."""
    folder = tmp_path_factory.mktemp("a1_demo_data")
    make_demo_data(["--n-points", str(N_DEMO_POINTS), "--seed", "0", "--out", str(folder)])
    return folder


def _settings_builder(demo_dir: Path, folder: Path):
    """The builder behind :func:`a1_settings`, writing its files into ``folder``."""

    def build(main_overrides=None, *, as_file=False, groups=None, static=False, **overrides):
        # static: the demo laid out like the real data - percentiles already in the static file.
        main_name, settings_name = (
            ("demo_static_main_config.yml", "a1_demo_static.yml") if static else ("demo_main_config.yml", "a1_demo.yml")
        )
        main = yaml.safe_load((A1_CONFIGS / main_name).read_text())
        common = main["common"]
        common["data"]["root"] = str(demo_dir)
        for key in (
            "DATA_SPEC_PATH",
            "SKLEARN_CONFIG_PATH",
            "LIGHTNING_CONFIG_PATH",
            "SKLEARN_REGISTRY_PATH",
            "LIGHTNING_REGISTRY_PATH",
        ):
            common[key] = str((A1_CONFIGS / common[key]).resolve())
        for key, value in (main_overrides or {}).items():
            common[key] = value
        main_path = folder / "main_config.yml"
        main_path.write_text(yaml.safe_dump(main))

        raw = yaml.safe_load((A1_CONFIGS / settings_name).read_text())
        raw["main_config"] = str(main_path)
        raw["data"] = {**raw["data"], "root": str(demo_dir)}
        if (main_overrides or {}).get("data"):
            raw["data"] = {key: main_overrides["data"][key] for key in raw["data"] if key in main_overrides["data"]}
        groups_path = A1_CONFIGS / raw["covariate_groups"]
        if groups is not None:
            groups_path = folder / "covariate_groups.yml"
            groups_path.write_text(yaml.safe_dump(groups, sort_keys=False))
        raw["covariate_groups"] = str(groups_path)
        raw.update(overrides)
        if as_file:
            path = folder / "a1.yml"
            path.write_text(yaml.safe_dump(raw, allow_unicode=True, sort_keys=False))
            return path
        return settings_from_mapping(raw)

    return build


@pytest.fixture
def a1_settings(a1_demo_dir, tmp_path):
    """Build A1 settings over the demo dataset; keyword arguments override the shipped demo file.

    The main configuration is the shipped ``configs/a1/demo_main_config.yml`` with the data folder
    pointed at the generated dataset and every other path made absolute, so the test does not depend
    on the directory pytest runs from. ``main_overrides`` edits its ``common`` block; ``groups``
    replaces the covariate groups; ``as_file=True`` writes the settings to a file and returns its
    path, for :func:`~yg_eo_soilnet.a1.config.load_a1_config`; ``static=True`` starts from the static
    demo instead (``a1_demo_static.yml``: the percentiles already in the static file, no time series).
    """
    return _settings_builder(a1_demo_dir, tmp_path)


@pytest.fixture(scope="session")
def a1_demo_settings(a1_demo_dir, tmp_path_factory):
    """The shipped demo settings over the demo dataset, built once, for module-scoped fixtures."""
    return _settings_builder(a1_demo_dir, tmp_path_factory.mktemp("a1_demo_settings"))()


@pytest.fixture(scope="session")
def a1_settings_in(a1_demo_dir):
    """:func:`a1_settings` for module-scoped fixtures: ``a1_settings_in(folder)`` gives the builder."""
    return lambda folder: _settings_builder(a1_demo_dir, Path(folder))


@pytest.fixture(autouse=True)
def _restore_logging():
    """Undo what an A1 script's setup_logging did to the root logger, so no test leaks its log file.

    setup_logging(force=True) replaces the root logger's handlers - pytest's own included - and opens
    a log file in the test's folder; left in place, every later test would write into it.
    """
    from yg_eo_soilnet.a1.logs import NOISY_LOGGERS

    root = logging.getLogger()
    handlers, level = list(root.handlers), root.level
    noisy = {name: logging.getLogger(name).level for name in NOISY_LOGGERS}
    yield
    for handler in list(root.handlers):
        if handler not in handlers:
            root.removeHandler(handler)
            handler.close()
    for handler in handlers:
        if handler not in root.handlers:
            root.addHandler(handler)
    root.setLevel(level)
    for name, previous in noisy.items():
        logging.getLogger(name).setLevel(previous)
